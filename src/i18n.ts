const dicts: Record<Lang, Dict> = { tr, en };

export function t(key: string, params: Record<string, unknown> = {}): string {
  const s = dicts[lang.value][key] ?? dicts.tr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] === undefined || params[k] === null ? '' : String(params[k])));
}

export function has(key: string) { return key in dicts[lang.value] || key in dicts.tr; }

const units: Record<Lang, [number, string][]> = {
  tr: [[1e12, 'Tn'], [1e9, 'Mr'], [1e6, 'Mn'], [1e3, 'B']],
  en: [[1e12, 'T'], [1e9, 'B'], [1e6, 'M'], [1e3, 'k']],
};

export function nf(v: number, digits = 0) {
  return new Intl.NumberFormat(lang.value === 'tr' ? 'tr-TR' : 'en-GB', { maximumFractionDigits: digits, minimumFractionDigits: 0 }).format(v);
}

/** ₺1,25 Mr / ₺1.25B */
export function money(v: number | null | undefined, opts: { sign?: boolean } = {}) {
  if (v === null || v === undefined || Number.isNaN(v)) return '—';
  const neg = v < 0;
  const a = Math.abs(v);
  let s: string;
  const u = units[lang.value].find(([d]) => a >= d);
  if (u && a >= 1e4) {
    const x = a / u[0];
    s = `${nf(x, x < 10 ? 2 : x < 100 ? 1 : 0)} ${u[1]}`;
  } else s = nf(a, 0);
  return `${neg ? '−' : opts.sign ? '+' : ''}₺${s}`;
}

export function pct(v: number, digits = 0) { return `%${nf(v * 100, digits)}`.replace(/^%(.*)$/, lang.value === 'tr' ? '%$1' : '$1%'); }

const MONTHS: Record<Lang, string[]> = {
  tr: ['Oca', 'Şub', 'Mar', 'Nis', 'May', 'Haz', 'Tem', 'Ağu', 'Eyl', 'Eki', 'Kas', 'Ara'],
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
};

/** Game hours -> "14 Mar 2026 08:30" */
export function gameDate(hours: number, startDate = '2026-01-01', withTime = true) {
  const d = new Date(`${startDate}T00:00:00Z`);
  d.setTime(d.getTime() + hours * 3600_000);
  const m = MONTHS[lang.value][d.getUTCMonth()];
  const base = `${d.getUTCDate()} ${m} ${d.getUTCFullYear()}`;
  if (!withTime) return base;
  return `${base} ${String(d.getUTCHours()).padStart(2, '0')}:${String(d.getUTCMinutes()).padStart(2, '0')}`;
}

export function duration(hours: number) {
  if (hours < 1) return `${Math.round(hours * 60)} ${t('common.min')}`;
  const d = Math.floor(hours / 24), h = Math.round(hours - d * 24);
  if (lang.value === 'tr') return d ? `${d} g ${h} sa` : `${h} sa`;
  return d ? `${d} d ${h} h` : `${h} h`;
}

export function minutes(m: number) {
  if (m < 60) return `${nf(m, m < 10 ? 1 : 0)} ${t('common.min')}`;
  const h = Math.floor(m / 60), mm = Math.round(m - h * 60);
  return lang.value === 'tr' ? `${h} sa ${mm} dk` : `${h} h ${mm} min`;
}

/** Translate an engine error into a message. */
export function errorText(e: any): string {
  const code: string = e?.code ?? e?.message ?? String(e);
  const detail = e?.detail ?? {};
  if (code.startsWith('level_required:')) return t('common.level_required', { n: code.split(':')[1] });
  const key = `err.${code}`;
  if (has(key)) {
    const params: Record<string, unknown> = { ...(typeof detail === 'object' ? detail : {}), detail: typeof detail === 'string' ? detail : '' };
    if (params.need !== undefined) params.need = money(Number(params.need));
    if (params.available !== undefined) params.available = money(Number(params.available));
    return t(key, params);
  }
  return t('err.unknown', { code });
}

export function noteText(note: string | null | undefined): string {
  if (!note) return '';
  const [k, v] = note.split(':');
  if (k === 'min_fee') { const [a, b] = (v || '').split('/'); return t('note.min_fee', { v: a, w: b }); }
  if (has(`note.${k}`)) return t(`note.${k}`, { v: v ? money(Number(v)) : '' });
  if (has(`err.${note}`)) return t(`err.${note}`);
  return note;
}
